import { NextResponse, type NextRequest } from "next/server";
import { createClient } from "@/lib/supabase/server";
import { supabaseConfig } from "@/lib/supabase/env";

/** Handles the link in Supabase confirmation / recovery emails (PKCE code exchange). */
export async function GET(request: NextRequest) {
  if (!supabaseConfig()) {
    return NextResponse.redirect(new URL("/setup", request.url));
  }

  const { searchParams, origin } = new URL(request.url);
  const code = searchParams.get("code");
  const next = searchParams.get("next") ?? "/";

  const forwardedHost = request.headers.get("x-forwarded-host");
  const forwardedProto = request.headers.get("x-forwarded-proto") ?? "https";
  const base = forwardedHost ? `${forwardedProto}://${forwardedHost}` : origin;

  if (code) {
    const supabase = await createClient();
    const { error } = await supabase.auth.exchangeCodeForSession(code);
    if (!error) return NextResponse.redirect(`${base}${next.startsWith("/") ? next : "/"}`);
  }

  return NextResponse.redirect(`${base}/login?error=link`);
}
